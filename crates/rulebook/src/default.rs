pub const DEFAULT_RULEBOOK: &str = "\
# 消息面规则手册

本系统关注加密货币市场消息：交易所动态、项目与代币事件、监管政策、宏观利率与资金流向。
下面按影响程度把消息分为四级，模型分级时按此判断；与加密货币市场无关的内容一律归档。

## 紧急

会立刻影响资金安全或市场价格、需要马上知道的消息。
- 交易所或大型协议被盗、遭黑客攻击
- 交易所暂停提现或充值
- 主流币发生重大安全事件（如链停摆、严重漏洞被利用）
- 监管突发行动（如起诉主要交易所、突然禁令）

## 重要

对市场或持仓有明显影响，需要当天关注的消息。
- 主流交易所上新币或下架代币
- 现货 ETF 获批、被拒或资金大额流入流出
- 美联储等央行的利率决议
- 大额融资、重要并购

## 一般

有一定参考价值但不紧迫的消息。
- 交易所常规公告、维护通知
- 项目的活动、版本更新、路线图进展

## 归档

不需要提醒，只留存备查。
- 营销推广、空投广告、带单喊单
- 与加密货币市场无关的内容

## 硬规则
- 紧急：暂停提现、被盗、hack、exploit、遭黑客攻击
- 重要：SEC 起诉、ETF 获批、大额融资

## 关键词
- 紧急：下架、delist
- 重要：上线、listing、利率决议
- 一般：公告、announcement、活动
";
